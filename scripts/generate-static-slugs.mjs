/**
 * Runs before `next build` (npm prebuild).
 * Bakes union of seed + Supabase slugs into lib/static-car-slugs.ts for client routing.
 */
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "lib/static-car-slugs.ts";

function readSeedSlugs() {
  const carsTs = readFileSync("data/cars.ts", "utf8");
  return [...carsTs.matchAll(/slug:\s*"([^"]+)"/g)].map((m) => m[1]);
}

async function readSupabaseSlugs() {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !key) {
    console.warn("[prebuild] Supabase env missing — seed slugs only");
    return [];
  }

  try {
    const res = await fetch(`${url}/rest/v1/cars?select=slug`, {
      headers: {
        apikey: key,
        Authorization: `Bearer ${key}`,
      },
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const rows = await res.json();
    if (!Array.isArray(rows)) return [];
    return rows.map((r) => r.slug).filter(Boolean);
  } catch (err) {
    console.warn(
      "[prebuild] Supabase fetch failed — seed slugs only:",
      err instanceof Error ? err.message : err
    );
    return [];
  }
}

const slugs = new Set(readSeedSlugs());
for (const slug of await readSupabaseSlugs()) slugs.add(slug);

const sorted = [...slugs].sort();

const content = `// Auto-generated by scripts/generate-static-slugs.mjs — do not edit manually
export const BUILD_TIME_CAR_SLUGS: readonly string[] = ${JSON.stringify(sorted, null, 2)};

export function isStaticCarSlug(slug: string): boolean {
  return BUILD_TIME_CAR_SLUGS.includes(slug);
}
`;

writeFileSync(OUT, content);
console.log(`[prebuild] Wrote ${sorted.length} static car slugs → ${OUT}`);
